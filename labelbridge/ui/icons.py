@lru_cache(maxsize=512)
def pixmap(name: str, color: str = Color.ICON, size: int = 18, ratio: float = 2.0) -> QPixmap:
    body = PATHS.get(name, PATHS["file"])
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    px = QPixmap(QSize(round(size * ratio), round(size * ratio)))
    px.fill(Qt.GlobalColor.transparent)
    painter = QPainter(px)
    renderer.render(painter)
    painter.end()
    px.setDevicePixelRatio(ratio)
    return px


def icon(name: str, color: str = Color.ICON, size: int = 18) -> QIcon:
    return QIcon(pixmap(name, color, size))


def _brand_icon_file(size: int):
    """PNG de marca generado por packaging/make_icon.py (el más pequeño que cubra el tamaño)."""
    from ..paths import resource_path

    folder = resource_path("assets", "icons")
    candidates = sorted(
        (int(p.stem.split("-")[-1]), p) for p in folder.glob("app-*.png") if p.stem.split("-")[-1].isdigit()
    ) if folder.is_dir() else []
    for available, path in candidates:
        if available >= size:
            return path
    return candidates[-1][1] if candidates else None


def app_icon_pixmap(size: int = 256) -> QPixmap:
    path = _brand_icon_file(size)
    if path is not None:
        pixmap = QPixmap(str(path))
        if not pixmap.isNull():
            if pixmap.width() != size:
                pixmap = pixmap.scaled(
                    size, size, Qt.AspectRatioMode.KeepAspectRatio, Qt.TransformationMode.SmoothTransformation
                )
            return pixmap
    return generic_icon_pixmap(size)


def generic_icon_pixmap(size: int = 256) -> QPixmap:
    """Icono genérico de LabelBridge (si falta el logo): etiqueta con código de barras sobre negro y oro."""
    px = QPixmap(size, size)
    px.fill(Qt.GlobalColor.transparent)
    p = QPainter(px)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    s = size / 256.0
    gradient = QLinearGradient(0, 0, size, size)
    gradient.setColorAt(0, QColor("#2A2A2A"))
    gradient.setColorAt(1, QColor("#121212"))
    p.setBrush(gradient)
    p.setPen(Qt.PenStyle.NoPen)
    p.drawRoundedRect(QRectF(8 * s, 8 * s, 240 * s, 240 * s), 56 * s, 56 * s)

    label = QPainterPath()
    label.addRoundedRect(QRectF(58 * s, 40 * s, 140 * s, 176 * s), 16 * s, 16 * s)
    p.setBrush(QColor("white"))
    p.drawPath(label)
    p.setBrush(QColor("#B98A2C"))
    p.drawEllipse(QRectF(116 * s, 56 * s, 24 * s, 24 * s))
    p.setBrush(QColor("#1A1A1A"))
    x = 78.0
    for w in (6, 3, 9, 3, 6, 12, 3, 6, 3, 9, 6, 3):
        p.drawRect(QRectF(x * s, 104 * s, w * s, 64 * s))
        x += w + 4.2
    p.setBrush(QColor("#E8B04B"))
    p.drawRoundedRect(QRectF(78 * s, 182 * s, 100 * s, 12 * s), 6 * s, 6 * s)
    p.end()
    return px


def app_icon() -> QIcon:
    icon_ = QIcon()
    for size in (16, 24, 32, 48, 64, 128, 256):
        icon_.addPixmap(app_icon_pixmap(size))
    return icon_
